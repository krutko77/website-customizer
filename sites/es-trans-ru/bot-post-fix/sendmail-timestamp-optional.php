/**
 * Проверка подписанной метки времени.
 *
 * Как и остальные антибот-проверки, при неудаче обработчик отвечает тихим
 * «успехом» — чтобы бот не понял, что его отсекли.
 *
 * ОТКАЗОУСТОЙЧИВОСТЬ: если секрет не настроен, проверка отключается.
 * Иначе полузаполненный конфиг положил бы приём заявок целиком.
 */
function formTokenOk(array $config): bool
{
    $secret = (string)($config['form_token']['secret'] ?? '');
    if ($secret === '' || $secret === 'ВСТАВЬТЕ_СЛУЧАЙНУЮ_СТРОКУ_64_СИМВОЛА') {
        return true;   // не настроено — не мешаем
    }

    $raw = (string)($_POST['form_token'] ?? '');
    if ($raw === '' || substr_count($raw, '.') !== 1) {
        return false;
    }

    [$ts, $sig] = explode('.', $raw, 2);

    if (!ctype_digit($ts)) {
        return false;
    }

    // hash_equals — сравнение за постоянное время, защита от подбора подписи
    // по времени ответа.
    $expected = hash_hmac('sha256', $ts, $secret);
    if (!hash_equals($expected, $sig)) {
        return false;
    }

    $age = time() - (int)$ts;
    $min = (int)($config['form_token']['min_seconds'] ?? 3);
    $max = (int)($config['form_token']['max_seconds'] ?? 7200);

    // Слишком быстро — бот. Слишком давно — метку переиспользуют.
    // Отрицательный age означает метку из будущего: подделка либо
    // разъехавшиеся часы.
    return $age >= $min && $age <= $max;
}

