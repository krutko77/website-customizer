 * ЭТО НЕ ГОТОВЫЙ ФАЙЛ ДЛЯ ЗАЛИВКИ. Это фрагменты, которые нужно внести в
 * sendmail.php и в вёрстку, если защит из основного патча окажется мало.
 *
 * ---------------------------------------------------------------------
 * ЗАЧЕМ
 * ---------------------------------------------------------------------
 * Человек не заполнит форму быстрее чем за несколько секунд. Бот
 * отправляет мгновенно. Проверяем, сколько прошло между отдачей страницы
 * и отправкой формы.
 *
 * ---------------------------------------------------------------------
 * ПОЧЕМУ МЕТКУ НАДО ПОДПИСЫВАТЬ
 * ---------------------------------------------------------------------
 * Наивный вариант — <input type="hidden" name="ts" value="1756200000">.
 * Он бесполезен: бот подставит любое значение, хоть вчерашнее.
 * Поэтому метка идёт вместе с подписью HMAC на серверном секрете —
 * подделать её, не зная секрета, нельзя.
 *
 * ---------------------------------------------------------------------
 * ЦЕНА
 * ---------------------------------------------------------------------
 * Требует правки ВЁРСТКИ и пересборки Gulp: поле нужно добавить во все три
 * формы, а значение — генерировать на сервере. Страницы сайта статические
 * (.html), поэтому метку придётся отдавать отдельным запросом или делать
 * страницы форм динамическими (.php). Это существенно дороже основного
 * патча — поэтому и вынесено в опцию.
 */


