/**
 * Возвращает подписанную метку времени для скрытого поля формы.
 * Формат: <unixtime>.<hmac>
 */
function makeFormToken(string $secret): string
{
    $ts = (string)time();
    return $ts . '.' . hash_hmac('sha256', $ts, $secret);
}

/*
    В шаблоне формы:

    <input type="hidden" name="form_token"
           value="<?= htmlspecialchars(makeFormToken($config['form_token']['secret']), ENT_QUOTES) ?>">
*/


